/* One-tap word lookup and drag-to-sentence selection for Lexora. */
(()=>{"use strict";
const roots=new WeakSet();
function getRange(doc,x,y){
 let pos=null;
 if(doc.caretPositionFromPoint){pos=doc.caretPositionFromPoint(x,y);if(pos)return {node:pos.offsetNode,offset:pos.offset}}
 if(doc.caretRangeFromPoint){const r=doc.caretRangeFromPoint(x,y);if(r)return {node:r.startContainer,offset:r.startOffset}}
 return null
}
function sentenceRange(doc,sel){
 if(!sel||sel.isCollapsed||!sel.rangeCount)return null;
 const r=sel.getRangeAt(0),p=(r.startContainer.nodeType===1?r.startContainer:r.startContainer.parentElement)?.closest("p");
 if(!p||!p.contains(r.endContainer))return null;
 const full=p.textContent||"",start=r.startOffset,end=r.endOffset;
 // Sentence spans are already generated by the reader when available.
 const a=(r.startContainer.nodeType===1?r.startContainer:r.startContainer.parentElement)?.closest(".lex-tappable");
 const b=(r.endContainer.nodeType===1?r.endContainer:r.endContainer.parentElement)?.closest(".lex-tappable");
 if(a&&b&&a.parentElement===b.parentElement){
  const result=doc.createRange();result.setStartBefore(a);result.setEndAfter(b);return result
 }
 return null
}
function handleSelection(doc,root,lookup){
 const sel=doc.getSelection();if(!sel||sel.isCollapsed)return false;
 const selected=sel.toString().trim();if(!selected)return false;
 const expanded=sentenceRange(doc,sel);
 if(expanded){sel.removeAllRanges();sel.addRange(expanded)}
 const value=sel.toString().trim().slice(0,800);
 const node=sel.anchorNode;
 const source=(node?.nodeType===1?node:node?.parentElement)?.closest?.("p")?.textContent||value;
 lookup(value,source);return true
}
function bind(doc,root,lookup){
 if(roots.has(root))return;roots.add(root);
 let down=null,moved=false;
 root.addEventListener("pointerdown",e=>{if(e.button!==0&&e.pointerType==="mouse")return;down={x:e.clientX,y:e.clientY};moved=false},true);
 root.addEventListener("pointermove",e=>{if(down&&Math.hypot(e.clientX-down.x,e.clientY-down.y)>7)moved=true},true);
 root.addEventListener("mouseup",e=>{
  // Capture before the original guide handler, avoiding duplicate lookups.
  if(handleSelection(doc,root,lookup)){e.stopImmediatePropagation();return}
 },true);
 root.addEventListener("click",e=>{
  if(e.detail>1||moved||e.target.closest("a,button,input,select"))return;
  const sel=doc.getSelection();if(sel&&!sel.isCollapsed)return;
  const pos=getRange(doc,e.clientX,e.clientY);if(!pos||pos.node.nodeType!==3)return;
  const text=pos.node.textContent||"";let i=Math.min(pos.offset,Math.max(0,text.length-1));
  if(!/[A-Za-z'-]/.test(text[i])&&i>0&&/[A-Za-z'-]/.test(text[i-1]))i--;
  if(!/[A-Za-z]/.test(text[i]))return;
  let a=i,b=i+1;while(a>0&&/[A-Za-z'-]/.test(text[a-1]))a--;while(b<text.length&&/[A-Za-z'-]/.test(text[b]))b++;
  const word=text.slice(a,b).replace(/^['-]+|['-]+$/g,"");if(!word)return;
  const node=pos.node.parentElement,para=node.closest("p");
  const source=para?.textContent||word;
  lookup(word,source);
 },true);
 root.addEventListener("touchend",()=>{setTimeout(()=>{if(handleSelection(doc,root,lookup)){}},170)},true);
}
const guide=document.getElementById("guide");
if(guide)bind(document,guide,(term,ctx)=>window.choose?.(term,ctx));
function bindEpub(){const frame=document.querySelector("#epub-view iframe");if(!frame)return;try{
 const d=frame.contentDocument;if(!d?.body)return;
 bind(d,d.body,(term,ctx)=>window.choose?.(term,ctx))
 }catch{}}
const view=document.getElementById("epub-view");
if(view){new MutationObserver(bindEpub).observe(view,{childList:true,subtree:true});view.addEventListener("load",()=>setTimeout(bindEpub,100),true)}
bindEpub();
})();